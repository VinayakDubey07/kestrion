"""
kestrion — command line interface.

Entry point registered in pyproject.toml as:
    [project.scripts]
    kestrion = "kestrion.cli.main:main"

Commands:
    kestrion init              scaffold a new agent project
    kestrion run <file>        run an agent script
    kestrion deploy --target   generate deployment manifests

Uses stdlib argparse only — no click/typer dependency, consistent with
the project's "optional extras for optional things" philosophy.
"""

