AGENT_TEMPLATE = '''\
"""
A Kestrion agent — generated by `kestrion init`.
Edit this file, then run it with `kestrion run agent.py`.
"""

import asyncio
from kestrion.agent.agent import Agent
from kestrion.agent.decorators import tool
from kestrion.llm.anthropic_provider import AnthropicProvider  # or OpenAI, Ollama


@tool
def get_status() -> dict:
    """Check the current status of something."""
    return {"status": "ok"}


@tool(requires_approval=True)
def do_something(target: str) -> dict:
    """Perform an action. Requires approval before executing."""
    return {"done": True, "target": target}


async def main():
    agent = Agent(
        provider=AnthropicProvider(model="claude-sonnet-4-6"),
        tools=[get_status, do_something],
        store="sqlite:///agent_runs.db",
    )
    result = await agent.run("Check the status and do something if needed.")
    print("status:", result.status)
    print("output:", result.output)


if __name__ == "__main__":
    asyncio.run(main())
'''

GITIGNORE_TEMPLATE = """\
# Kestrion
*.db
*.db-shm
*.db-wal
agent_runs.db

# Python
__pycache__/
*.pyc
.venv/
dist/
build/
"""


def cmd_init(args: argparse.Namespace) -> int:
    target = Path(args.directory) if args.directory else Path.cwd()
    target.mkdir(parents=True, exist_ok=True)

    agent_file = target / "agent.py"
    gitignore_file = target / ".gitignore"

    if agent_file.exists() and not args.force:
        print(f"error: {agent_file} already exists. Use --force to overwrite.", file=sys.stderr)
        return 1

    agent_file.write_text(AGENT_TEMPLATE)
    print(f"created {agent_file}")

    if not gitignore_file.exists():
        gitignore_file.write_text(GITIGNORE_TEMPLATE)
        print(f"created {gitignore_file}")

    print()
    print("Next steps:")
    print(f"  cd {target}")
    print("  pip install kestrion[anthropic]   # or [openai] or [ollama]")
    print("  kestrion run agent.py")
    return 0


