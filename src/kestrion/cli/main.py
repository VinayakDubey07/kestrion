def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="kestrion",
        description="Kestrion — durable AI agent framework",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""\
            examples:
              kestrion init                     scaffold a new agent in the current directory
              kestrion init ./my-agent          scaffold in a subdirectory
              kestrion run agent.py             run an agent script
              kestrion deploy --target k8s      generate Kubernetes manifests
              kestrion trace <run_id>           view a run's event timeline
              kestrion dashboard                start the web dashboard
        """),
    )
    try:
        import importlib.metadata
        version = importlib.metadata.version("kestrion")
    except Exception:
        version = "0.6.0"
    parser.add_argument("--version", action="version", version=f"%(prog)s {version}")

    sub = parser.add_subparsers(dest="command", metavar="<command>")

    # init
    p_init = sub.add_parser("init", help="scaffold a new Kestrion agent project")
    p_init.add_argument("directory", nargs="?", help="directory to scaffold into (default: current)")
    p_init.add_argument("--force", action="store_true", help="overwrite existing files")

    # run
    p_run = sub.add_parser("run", help="run an agent script")
    p_run.add_argument("file", help="path to the agent Python file")
    p_run.add_argument("-v", "--verbose", action="store_true", help="show full tracebacks on error")

    # deploy
    p_deploy = sub.add_parser("deploy", help="generate deployment manifests")
    p_deploy.add_argument("--target", required=True, choices=["k8s"], help="deployment target (only k8s for now)")
    p_deploy.add_argument("--name", help="agent/deployment name (default: current directory name)")
    p_deploy.add_argument("--image", help="container image (default: your-registry/<name>:latest)")
    p_deploy.add_argument("--namespace", default="default", help="Kubernetes namespace (default: default)")
    p_deploy.add_argument("--model", default="claude-sonnet-4-6", help="LLM model name")
    p_deploy.add_argument("--store", help="store URL (default: sqlite:////data/agent.db)")
    p_deploy.add_argument("--system-prompt", dest="system_prompt", default="", help="agent system prompt")
    p_deploy.add_argument("--file", help="agent script filename (for Dockerfile, default: agent.py)")
    p_deploy.add_argument("--provider", default="anthropic", help="LLM provider extra (for Dockerfile)")
    p_deploy.add_argument("--output", help="output filename (default: <name>-k8s.yaml)")
    p_deploy.add_argument("--force", action="store_true", help="overwrite existing Dockerfile")

    # trace
    p_trace = sub.add_parser("trace", help="inspect a run's event timeline")
    p_trace.add_argument("run_id", help="the run ID to trace")
    p_trace.add_argument("--store", help="path to the SQLite database file (default: kestrion_runs.db)")
    p_trace.add_argument("--type", help="filter events by type (e.g. tool_call_started)")
    p_trace.add_argument("--node", help="filter events by node (e.g. agent_loop)")
    p_trace.add_argument("--mermaid", action="store_true", help="output trace as a Mermaid flowchart diagram")

    # list
    p_list = sub.add_parser("list", help="list all runs in the database")
    p_list.add_argument("--store", help="path to the SQLite database file (default: kestrion_runs.db)")

    # resume
    p_resume = sub.add_parser("resume", help="resume a paused or crashed run")
    p_resume.add_argument("run_id", help="the run ID to resume")
    p_resume.add_argument("file", help="path to the agent Python file")
    p_resume.add_argument("-v", "--verbose", action="store_true", help="show full tracebacks on error")

    # chat
    p_chat = sub.add_parser("chat", help="interactively chat with an agent")
    p_chat.add_argument("file", help="path to the agent Python file")
    p_chat.add_argument("-v", "--verbose", action="store_true", help="show full tracebacks on error")

    # dashboard
    p_dash = sub.add_parser("dashboard", help="start the web dashboard server")
    p_dash.add_argument("file", nargs="?", help="optional path to the agent Python file for interactive chat")
    p_dash.add_argument("--host", default="127.0.0.1", help="host to bind the server to (default: 127.0.0.1)")
    p_dash.add_argument("--port", type=int, default=8000, help="port to bind the server to (default: 8000)")
    p_dash.add_argument("--store", help="path to the SQLite database file (default: kestrion_runs.db)")

    # fork
    p_fork = sub.add_parser("fork", help="time-travel by branching off a past run")
    p_fork.add_argument("run_id", help="the run ID to fork")
    p_fork.add_argument("--at-seq", type=int, required=True, help="the event sequence count to fork at")
    p_fork.add_argument("--store", help="path to the SQLite database file (default: kestrion_runs.db)")

    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    if args.command is None:
        parser.print_help()
        sys.exit(0)

    handlers = {
        "init": cmd_init,
        "run": cmd_run,
        "deploy": cmd_deploy,
        "trace": cmd_trace,
        "dashboard": cmd_dashboard,
        "fork": cmd_fork,
        "list": cmd_list,
        "resume": cmd_resume,
        "chat": cmd_chat,
    }
    sys.exit(handlers[args.command](args))


if __name__ == "__main__":
    main()