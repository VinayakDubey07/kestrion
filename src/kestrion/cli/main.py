def cmd_deploy(args: argparse.Namespace) -> int:
    from kestrion.cli.deploy import generate_dockerfile, generate_k8s_manifest

    if args.target != "k8s":
        print(f"error: unsupported target '{args.target}'. Only 'k8s' is supported today.", file=sys.stderr)
        return 1

    name = args.name or Path.cwd().name.lower().replace("_", "-").replace(" ", "-")
    output = args.output or f"{name}-k8s.yaml"
    dockerfile_out = Path("Dockerfile")

    manifest = generate_k8s_manifest(
        name=name,
        image=args.image or f"your-registry/{name}:latest",
        namespace=args.namespace or "default",
        model=args.model or "claude-sonnet-4-6",
        store_url=args.store or "sqlite:////data/agent.db",
        system_prompt=args.system_prompt or "",
        output_file=output,
    )

    Path(output).write_text(manifest)
    print(f"generated {output}")

    if not dockerfile_out.exists() or args.force:
        script = args.file or "agent.py"
        provider = args.provider or "anthropic"
        dockerfile_out.write_text(generate_dockerfile(script=script, provider=provider))
        print("generated Dockerfile")

    print()
    print("Next steps:")
    print(f"  1. Fill in the real image name in {output} (search REPLACE_WITH_REAL_KEY too)")
    print("  2. Build and push your image:")
    print(f"       docker build -t your-registry/{name}:latest .")
    print(f"       docker push your-registry/{name}:latest")
    print("  3. Apply the manifest:")
    print(f"       kubectl apply -f {output}")
    return 0

def generate_mermaid_flowchart(events: list[Any], run_id: str) -> str:
    lines = ["flowchart TD", f"    %% Mermaid trace for run {run_id}"]
    nodes_seen = set()
    node_labels = {}
    transitions = []
    action_counter = 0

    nodes_seen.add("START")
    node_labels["START"] = "START"

    def clean_id(name: str | None) -> str:
        if not name:
            return "engine"
        return "".join(c if c.isalnum() or c == "_" else "_" for c in name)

    last_active_node = "START"

    for evt in events:
        raw_node = evt.node or "engine"
        node_id = clean_id(raw_node)
        if node_id not in nodes_seen:
            nodes_seen.add(node_id)
            node_labels[node_id] = f"Node: {raw_node}"
            
        if evt.node:
            last_active_node = node_id

        evt_type = evt.type.value
        payload = evt.payload or {}

        if evt_type == "run_started":
            entry = clean_id(payload.get("entry_node") or "engine")
            if entry not in nodes_seen:
                nodes_seen.add(entry)
                node_labels[entry] = f"Node: {payload.get('entry_node') or 'engine'}"
            transitions.append(f"    START --> {entry}")
            last_active_node = entry
        elif evt_type == "state_transition":
            from_node = clean_id(payload.get("from") or "START")
            to_node = clean_id(payload.get("to") or "END")
            if from_node not in nodes_seen:
                nodes_seen.add(from_node)
                node_labels[from_node] = f"Node: {payload.get('from') or 'START'}"
            if to_node not in nodes_seen:
                nodes_seen.add(to_node)
                node_labels[to_node] = f"Node: {payload.get('to') or 'END'}"
            transitions.append(f"    {from_node} --> {to_node}")
            last_active_node = to_node
        elif evt_type == "tool_call_started":
            action_counter += 1
            tool_name = payload.get("tool", "unknown")
            tool_id = f"tool_{action_counter}"
            lines.append(f'    {tool_id}(["Tool: {tool_name}"])')
            transitions.append(f"    {node_id} --> {tool_id}")
        elif evt_type == "llm_call_completed":
            action_counter += 1
            llm_id = f"llm_{action_counter}"
            prompt_toks = evt.tokens_in
            comp_toks = evt.tokens_out
            lines.append(f'    {llm_id}{{"LLM Call<br/>{prompt_toks} in / {comp_toks} out"}}')
            transitions.append(f"    {node_id} --> {llm_id}")
        elif evt_type == "human_intervention":
            action_counter += 1
            human_id = f"human_{action_counter}"
            tool = payload.get("tool", "")
            lines.append(f'    {human_id}[/"Human Gate: {tool}"/]')
            transitions.append(f"    {node_id} --> {human_id}")
        elif evt_type == "context_compacted":
            action_counter += 1
            comp_id = f"comp_{action_counter}"
            lines.append(f'    {comp_id}("Context Compacted")')
            transitions.append(f"    {node_id} --> {comp_id}")
        elif evt_type == "run_completed":
            transitions.append(f"    {last_active_node} --> END")
        elif evt_type == "run_failed":
            transitions.append(f"    {last_active_node} --> FAILED")

    for n_id, label in node_labels.items():
        if n_id == "START":
            lines.append("    START([START])")
        else:
            lines.append(f'    {n_id}["{label}"]')

    unique_transitions = list(dict.fromkeys(transitions))
    lines.extend(unique_transitions)

    # Conditionally declare and style terminal nodes if they are reached
    has_end = any("--> END" in t for t in unique_transitions)
    has_failed = any("--> FAILED" in t for t in unique_transitions)

    if has_end:
        lines.append("    END([END])")
        lines.append("    style END fill:#10b981,stroke:#047857,stroke-width:2px,color:#fff")
    if has_failed:
        lines.append("    FAILED([FAILED])")
        lines.append("    style FAILED fill:#ef4444,stroke:#b91c1c,stroke-width:2px,color:#fff")

    # Stylize START node
    lines.append("    style START fill:#10b981,stroke:#047857,stroke-width:2px,color:#fff")

    return "\n".join(lines)


def cmd_trace(args: argparse.Namespace) -> int:
    db_path = args.store or "kestrion_runs.db"
    db_file = Path(db_path)
    if not db_file.exists():
        if not args.store and Path("agent_runs.db").exists():
            db_path = "agent_runs.db"
            db_file = Path(db_path)
        else:
            print(f"error: database file '{db_path}' not found", file=sys.stderr)
            return 1

    from kestrion.store.sqlite_store import SQLiteCheckpointStore
    store = SQLiteCheckpointStore(path=db_path)

    async def get_data():
        events = await store.events_since(args.run_id, 0)
        checkpoint = await store.latest(args.run_id)
        return events, checkpoint

    try:
        events, checkpoint = asyncio.run(get_data())
    except Exception as exc:
        print(f"error loading run: {exc}", file=sys.stderr)
        return 1

    if not events:
        print(f"No events found for run_id: {args.run_id}", file=sys.stderr)
        return 1

    if getattr(args, "mermaid", False):
        print(generate_mermaid_flowchart(events, args.run_id))
        return 0

    # ANSI colors
    C_GREEN = "\033[92m"
    C_YELLOW = "\033[93m"
    C_RED = "\033[91m"
    C_CYAN = "\033[96m"
    C_MAGENTA = "\033[95m"
    C_RESET = "\033[0m"
    C_BOLD = "\033[1m"

    state = checkpoint.state if checkpoint else None
    status = state.status.value if state else "UNKNOWN"
    total_tokens = state.total_tokens if state else 0
    total_cost = state.total_cost_usd if state else 0.0

    color = C_RESET
    if status == "completed":
        color = C_GREEN
    elif status == "waiting_on_human":
        color = C_YELLOW
    elif status == "failed":
        color = C_RED
    elif status == "expired":
        color = C_MAGENTA

    print(f"{C_BOLD}Run ID: {args.run_id}{C_RESET} ({color}{C_BOLD}{status.upper()}{C_RESET})")
    print(f"Database: {db_path}")
    print(f"Total Tokens: {total_tokens} | Cost: ${total_cost:.5f}")
    print("-" * 80)

    for evt in events:
        if args.type and evt.type.value != args.type:
            continue
        if args.node and evt.node != args.node:
            continue

        ts = evt.timestamp.strftime("%Y-%m-%d %H:%M:%S")
        evt_type = evt.type.value.upper()
        
        if "FAILED" in evt_type or "EXPIRED" in evt_type:
            type_color = C_RED
        elif "STARTED" in evt_type:
            type_color = C_GREEN
        elif "COMPLETED" in evt_type:
            type_color = C_CYAN
        elif "HUMAN" in evt_type:
            type_color = C_YELLOW
        else:
            type_color = C_RESET

        node_str = f" [{evt.node}]" if evt.node else ""
        print(f"[{ts}] {type_color}{C_BOLD}{evt_type}{C_RESET}{node_str}")

        payload = evt.payload
        if evt.type.value == "message_received":
            print(f"  {C_YELLOW}User Prompt:{C_RESET} {payload.get('content')}")
        elif evt.type.value == "llm_call_completed":
            print(f"  {C_CYAN}LLM Response:{C_RESET} Stop Reason: {payload.get('stop_reason')} | Tokens: {evt.tokens_in} in / {evt.tokens_out} out | Cost: ${evt.cost_usd:.5f}")
        elif evt.type.value == "tool_call_started":
            print(f"  {C_CYAN}Tool Call:{C_RESET} {payload.get('tool')}({payload.get('args')})")
        elif evt.type.value == "tool_call_completed":
            out_str = str(payload.get("output"))
            if len(out_str) > 120:
                out_str = out_str[:120] + "..."
            print(f"  {C_GREEN}Tool Output:{C_RESET} {out_str}")
        elif evt.type.value == "tool_call_failed":
            print(f"  {C_RED}Tool Error:{C_RESET} {payload.get('error')}")
        elif evt.type.value == "state_transition":
            from_node = payload.get("from")
            to_node = payload.get("to")
            print(f"  {C_MAGENTA}Transition:{C_RESET} {from_node} -> {to_node}")
        elif evt.type.value == "human_intervention":
            tool = payload.get("tool")
            roles = payload.get("missing_roles")
            expires = payload.get("expires_at")
            print(f"  {C_YELLOW}Approval Required:{C_RESET} Tool '{tool}' | Missing Roles: {roles} | Expires: {expires}")
        elif evt.type.value == "checkpoint_saved":
            pass
        elif payload:
            print(f"  Payload: {payload}")
    return 0


